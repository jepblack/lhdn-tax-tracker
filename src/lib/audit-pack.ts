import JSZip from "jszip";
import { formatRM } from "./calculator";
import { getReliefCategories, getStatusReliefAmounts } from "./lhdn-rules";
import {
  buildArchiveBaseFilename,
  mapReliefToArchiveCategory,
} from "./receipt-archiver";
import {
  LhdnReceiptMetadata,
  TaxCalculationResult,
  TaxExpense,
  TaxProfile,
} from "./types";

/**
 * Generates a 1-click LHDN Audit Pack ZIP containing:
 * - Receipts_{YYYY}_LHDN_Index.csv
 * - Form_BE_YA{YYYY}_CheatSheet.txt
 * - Receipts/{YYYY}/*.json (metadata for every expense)
 * - Receipts/{YYYY}/*.pdf (for every accessible receipt file)
 * - Google_Drive_Receipts_Links.txt (if any receipts are stored directly in Google Drive)
 */
export async function exportAuditPackZip(
  profile: TaxProfile,
  summary: TaxCalculationResult,
  allExpenses: TaxExpense[]
): Promise<{ fileCount: number; zipName: string }> {
  const taxYear = profile.taxYear;
  const yearExpenses = allExpenses.filter((e) => e.taxYear === taxYear);
  const categories = getReliefCategories(taxYear);
  const catMap = new Map(categories.map((c) => [c.id, c]));
  const statusAmounts = getStatusReliefAmounts(taxYear);

  const zip = new JSZip();
  const folder = zip.folder(`Receipts/${taxYear}`)!;
  let fileCount = 0;

  // 1. Annual LHDN Index CSV
  const headers = [
    "filename",
    "date",
    "merchant",
    "amount",
    "currency",
    "category",
    "payment_method",
    "tax_amount",
    "ocr_confidence",
    "needs_review",
    "form_be_ref",
    "lhdn_relief",
    "receipt_number",
    "retain_until",
  ];

  const csvRows = yearExpenses.map((e) => {
    const cat = catMap.get(e.categoryId);
    const m = e.metadata;
    const baseName = buildArchiveBaseFilename({
      transactionDate: e.expenseDate,
      merchantName: e.merchant,
      amountPaid: e.amount,
      currency: m?.currency || "MYR",
      category:
        m?.category || mapReliefToArchiveCategory(e.categoryId, e.subCategoryId),
    });
    const pdfName = m?.file_pdf || e.receiptFileName || `${baseName}.pdf`;
    return [
      pdfName,
      m?.transaction_date || e.expenseDate,
      m?.merchant_name || e.merchant,
      (m?.amount_paid ?? e.amount).toFixed(2),
      m?.currency || "MYR",
      m?.category || cat?.shortName || e.categoryId,
      m?.payment_method || "",
      (m?.sst_or_tax_amount ?? 0).toFixed(2),
      m?.ocr_confidence || (e.aiExtracted ? "high" : "manual"),
      m?.needs_review ? "true" : "false",
      cat?.formBeRef || "",
      cat?.name || e.categoryId,
      m?.receipt_number || e.invoiceNumber || "",
      String(taxYear + 8),
    ];
  });

  const csvContent = [headers, ...csvRows]
    .map((r) => r.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(","))
    .join("\n");
  zip.file(`Receipts_${taxYear}_LHDN_Index.csv`, csvContent);
  fileCount++;

  // 2. Form BE Cheat Sheet Text Summary
  const formLines: string[] = [
    `LHDN MALAYSIA — FORM BE e-FILING SUMMARY (YA ${taxYear})`,
    `Generated by CukaiKu on ${new Date().toISOString().slice(0, 10)}`,
    `LHDN 7-Year Retention: Keep until ${taxYear + 8}`,
    `============================================================`,
    ``,
    `INCOME & TAX ESTIMATE`,
    `  Annual Income:        ${formatRM(summary.annualIncome, true)}`,
    `  Total Reliefs:      - ${formatRM(summary.totalReliefs, true)}`,
    `  Chargeable Income:    ${formatRM(summary.chargeableIncome, true)}`,
    `  Gross Income Tax:     ${formatRM(summary.grossTax, true)}`,
    `  Zakat / Fitrah:     - ${formatRM(summary.zakatRebate, true)}`,
    `  Small Income Rebate:- ${formatRM(summary.smallIncomeRebate, true)}`,
    `  Net Tax Payable:      ${formatRM(summary.netTaxPayable, true)}`,
    `  PCB / MTD Paid YTD:   ${formatRM(summary.pcbPaid, true)}`,
    `  Est. Refund / (Due):  ${formatRM(summary.estimatedRefund, true)}`,
    ``,
    `STATUS RELIEFS`,
    `  [F1] Individual:      ${formatRM(profile.statusReliefs.individual ? statusAmounts.individual : 0, true)}`,
    `  [F1a] Disabled Self:  ${formatRM(profile.statusReliefs.disabledIndividual ? statusAmounts.disabledIndividual : 0, true)}`,
    `  [F7] Spouse:          ${formatRM(profile.statusReliefs.spouse ? statusAmounts.spouse : 0, true)}`,
    `  [F8] Children Total:  ${formatRM(
      profile.statusReliefs.childrenUnder18 * statusAmounts.childUnder18 +
        profile.statusReliefs.childrenHigherEd * statusAmounts.childHigherEd +
        profile.statusReliefs.disabledChildren * statusAmounts.disabledChild,
      true
    )}`,
    ``,
    `EXPENSE RELIEFS (BY FORM BE BOX)`,
  ];

  for (const cs of summary.categorySummaries) {
    if (cs.claimable > 0) {
      formLines.push(
        `  [${cs.category.formBeRef.padEnd(3)}] ${cs.category.name.padEnd(42)} ${formatRM(cs.claimable, true)} (Cap ${formatRM(cs.category.maxLimit)})`
      );
    }
  }

  zip.file(`Form_BE_YA${taxYear}_CheatSheet.txt`, formLines.join("\n"));
  fileCount++;

  // 3. Per-receipt JSON metadata + PDF files
  const driveLinks: string[] = [];

  for (const exp of yearExpenses) {
    const baseName = buildArchiveBaseFilename({
      transactionDate: exp.expenseDate,
      merchantName: exp.merchant,
      amountPaid: exp.amount,
      currency: exp.metadata?.currency || "MYR",
      category:
        exp.metadata?.category ||
        mapReliefToArchiveCategory(exp.categoryId, exp.subCategoryId),
    });

    const metadata: LhdnReceiptMetadata = exp.metadata || {
      file_pdf: `${baseName}.pdf`,
      capture_date: exp.createdAt.slice(0, 10),
      transaction_date: exp.expenseDate,
      merchant_name: exp.merchant,
      merchant_registration_or_tax_id: "",
      receipt_number: exp.invoiceNumber || "",
      payment_method: "",
      card_last4: "",
      currency: "MYR",
      amount_paid: exp.amount,
      sst_or_tax_amount: 0,
      tax_inclusive: true,
      category: mapReliefToArchiveCategory(exp.categoryId, exp.subCategoryId),
      lhdn_relief_or_expense_type:
        catMap.get(exp.categoryId)?.name || exp.categoryId,
      items: [
        {
          description: exp.description || exp.merchant,
          quantity: 1,
          unit_price: exp.amount,
          amount: exp.amount,
        },
      ],
      ocr_confidence: exp.aiExtracted ? "high" : "medium",
      needs_review: !exp.receiptUrl && !exp.receiptPath,
      review_reason:
        !exp.receiptUrl && !exp.receiptPath ? "Missing receipt file" : "",
      original_file_hash: "",
      notes: exp.description || "",
    };

    const jsonFilename = metadata.file_pdf.replace(/\.pdf$/i, ".json");
    folder.file(jsonFilename, JSON.stringify(metadata, null, 2));
    fileCount++;

    if (exp.receiptUrl && exp.receiptUrl !== "sample://attached") {
      if (exp.receiptUrl.includes("drive.google.com")) {
        driveLinks.push(
          `${metadata.file_pdf} | ${exp.expenseDate} | ${exp.merchant} | RM ${exp.amount.toFixed(2)} | ${exp.receiptUrl}`
        );
      } else {
        try {
          const res = await fetch(exp.receiptUrl);
          if (res.ok) {
            const blob = await res.blob();
            const ext =
              blob.type === "application/pdf"
                ? ".pdf"
                : blob.type === "image/png"
                ? ".png"
                : ".jpg";
            const fileName = metadata.file_pdf.replace(/\.pdf$/i, ext);
            folder.file(fileName, blob);
            fileCount++;
          }
        } catch {
          // Skip unreachable remote URLs gracefully
        }
      }
    }
  }

  if (driveLinks.length > 0) {
    zip.file(
      "Google_Drive_Receipts_Links.txt",
      [
        `RECEIPTS ARCHIVED IN YOUR GOOGLE DRIVE (/CukaiKu/Receipts/${taxYear}/)`,
        `================================================================`,
        ...driveLinks,
      ].join("\n")
    );
    fileCount++;
  }

  const zipBlob = await zip.generateAsync({ type: "blob" });
  const zipName = `CukaiKu_LHDN_YA${taxYear}_Audit_Pack.zip`;
  const url = URL.createObjectURL(zipBlob);
  const link = document.createElement("a");
  link.href = url;
  link.download = zipName;
  link.click();
  URL.revokeObjectURL(url);

  return { fileCount, zipName };
}
